/**
 * Presets rítmicos y de textura de Orbit Prisma: voces, arpegios, atmósferas,
 * efectos, percusión y sonidos del mundo.
 *
 * Mismas reglas de autoría que el archivo melódico: las capas dicen de qué
 * está hecho, `base` deja las perillas donde el sonido ya funciona, y las
 * macros llevan nombre de lo que hacen al oído.
 *
 * Dos cosas que aquí se respetan a rajatabla porque si no el preset miente:
 * - `wave` del canal vale **0.5 = neutro**. No es "el wave de la capa 1": es un
 *   desplazamiento que se suma a TODAS las capas, así que ponerlo en otro sitio
 *   corre el timbre de la pila entera.
 * - Una macro **sobrescribe** el valor al disparar la nota. Si su valor por
 *   defecto no reproduce lo que dice `base` (o la capa), el preset suena
 *   distinto de lo que muestran las perillas. Aquí los rangos están calculados
 *   para que `min + (max - min) * valor` caiga justo en el valor declarado.
 */

